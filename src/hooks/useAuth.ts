import { useEffect, useState, useCallback } from 'react';
import type { User, Session } from '@supabase/supabase-js';
import { supabase, isConfigured } from '../lib/supabase';
import { localDb } from '../lib/db';
import type { Profile } from '../types/database';

export function useAuth() {
  const [user, setUser] = useState<User | null>(null);
  const [profile, setProfile] = useState<Profile | null>(null);
  const [session, setSession] = useState<Session | null>(null);
  const [loading, setLoading] = useState<boolean>(true);
  const [authError, setAuthError] = useState<string | null>(null);

  // Load profile from Supabase with IndexedDB fallback
  const fetchProfile = useCallback(async (userId: string): Promise<Profile | null> => {
    if (!isConfigured) {
      // Mock profile if not configured
      return {
        id: userId,
        username: 'DemoUser',
        avatar_url: `https://api.dicebear.com/7.x/bottts/svg?seed=DemoUser`,
        created_at: new Date().toISOString(),
      };
    }

    try {
      // 1. Check local cache first for instant render
      const cached = await localDb.profiles.get(userId);
      if (cached) {
        setProfile({
          id: cached.id,
          username: cached.username,
          avatar_url: cached.avatar_url,
          created_at: new Date(cached.updated_at).toISOString(),
        });
      }

      // 2. Fetch fresh profile from Supabase
      const { data, error } = await supabase
        .from('profiles')
        .select('*')
        .eq('id', userId)
        .single();

      if (error && error.code !== 'PGRST116') {
        console.error('Error fetching profile:', error);
      }

      if (data) {
        setProfile(data as Profile);
        await localDb.profiles.put({
          id: data.id,
          username: data.username,
          avatar_url: data.avatar_url,
          updated_at: Date.now(),
        });
        return data as Profile;
      } else if (userId) {
        // Fallback profile creation if not yet generated by trigger
        const defaultName =
          user?.user_metadata?.username || `user_${userId.slice(0, 5)}`;
        const { data: newProf } = await supabase
          .from('profiles')
          .upsert({
            id: userId,
            username: defaultName,
            avatar_url: `https://api.dicebear.com/7.x/bottts/svg?seed=${defaultName}`,
          })
          .select()
          .single();

        if (newProf) {
          setProfile(newProf as Profile);
          return newProf as Profile;
        }
      }
    } catch (err) {
      console.warn('Network error fetching profile, using cache:', err);
    }
    return null;
  }, []);

  // Listen to Supabase Auth state changes
  useEffect(() => {
    if (!isConfigured) {
      setLoading(false);
      return;
    }

    supabase.auth.getSession().then(({ data: { session } }) => {
      setSession(session);
      setUser(session?.user ?? null);
      if (session?.user) {
        fetchProfile(session.user.id).finally(() => setLoading(false));
      } else {
        setLoading(false);
      }
    });

    const {
      data: { subscription },
    } = supabase.auth.onAuthStateChange(async (_event, session) => {
      setSession(session);
      setUser(session?.user ?? null);
      if (session?.user) {
        await fetchProfile(session.user.id);
      } else {
        setProfile(null);
      }
      setLoading(false);
    });

    return () => {
      subscription.unsubscribe();
    };
  }, [fetchProfile]);

  // Sign up
  const signUp = async (email: string, password: string, username: string) => {
    setAuthError(null);
    if (!isConfigured) {
      setAuthError('Supabase is not configured yet. Please configure .env');
      return { error: new Error('Supabase not configured') };
    }

    try {
      const { data, error } = await supabase.auth.signUp({
        email,
        password,
        options: {
          data: {
            username: username.trim(),
          },
        },
      });

      if (error) {
        setAuthError(error.message);
        return { error };
      }

      if (data.user) {
        // Double check profile creation
        await fetchProfile(data.user.id);

        // Check if there is a pending invite code in sessionStorage
        const pendingInvite = sessionStorage.getItem('pending_invite_code');
        if (pendingInvite) {
          try {
            await supabase.rpc('join_group_with_code', { invite_code: pendingInvite });
            sessionStorage.removeItem('pending_invite_code');
          } catch (joinErr) {
            console.error('Error joining group after signup:', joinErr);
          }
        }
      }

      return { data, error: null };
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : 'Sign up failed';
      setAuthError(msg);
      return { error: err };
    }
  };

  // Sign in
  const signIn = async (email: string, password: string) => {
    setAuthError(null);
    if (!isConfigured) {
      setAuthError('Supabase is not configured yet. Please configure .env');
      return { error: new Error('Supabase not configured') };
    }

    try {
      const { data, error } = await supabase.auth.signInWithPassword({
        email,
        password,
      });

      if (error) {
        setAuthError(error.message);
        return { error };
      }

      if (data.user) {
        await fetchProfile(data.user.id);

        // Process pending invite if present
        const pendingInvite = sessionStorage.getItem('pending_invite_code');
        if (pendingInvite) {
          try {
            await supabase.rpc('join_group_with_code', { invite_code: pendingInvite });
            sessionStorage.removeItem('pending_invite_code');
          } catch (joinErr) {
            console.error('Error joining group after login:', joinErr);
          }
        }
      }

      return { data, error: null };
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : 'Sign in failed';
      setAuthError(msg);
      return { error: err };
    }
  };

  // Sign out
  const signOut = async () => {
    if (isConfigured) {
      await supabase.auth.signOut();
    }
    setUser(null);
    setProfile(null);
    setSession(null);
  };

  return {
    user,
    profile,
    session,
    loading,
    authError,
    setAuthError,
    signUp,
    signIn,
    signOut,
    refreshProfile: () => (user ? fetchProfile(user.id) : Promise.resolve(null)),
  };
}

